-- Schema is owned by Flyway; Hibernate only validates it (ddl-auto: validate).

CREATE TABLE customer (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL,
    tier    VARCHAR(20)  NOT NULL
);

CREATE TABLE product (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku      VARCHAR(40)    NOT NULL,
    name     VARCHAR(120)   NOT NULL,
    price    NUMERIC(12, 2) NOT NULL,
    stock    INTEGER        NOT NULL,
    version  BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_price CHECK (price >= 0),
    CONSTRAINT ck_product_stock CHECK (stock >= 0)
);

CREATE TABLE customer_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT         NOT NULL,
    status         VARCHAR(20)    NOT NULL,
    business_date  DATE           NOT NULL,
    subtotal       NUMERIC(12, 2) NOT NULL,
    discount       NUMERIC(12, 2) NOT NULL,
    created_at     TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);
CREATE INDEX ix_order_customer ON customer_order (customer_id);
CREATE INDEX ix_order_business_date ON customer_order (business_date);

CREATE TABLE order_line (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT         NOT NULL,
    product_id  BIGINT         NOT NULL,
    quantity    INTEGER        NOT NULL,
    unit_price  NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_line_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT fk_line_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_line_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_line_order ON order_line (order_id);
CREATE INDEX ix_line_product ON order_line (product_id);
